// build-client.mjs — bundle src/client/index.tsx into a DSH-loadable lib/client.js
// The output registers itself through window.__ModuleLoader__.load, so the DSH
// client shell can pick it up as the Browser half of the plugin.
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const tmp = path.join(root, "lib", ".client.cjs.js");
const out = path.join(root, "lib", "client.js");

await build({
  entryPoints: [path.join(root, "src", "client", "index.tsx")],
  bundle: true,
  format: "cjs",
  platform: "browser",
  target: "es2020",
  jsx: "transform",
  loader: { ".css": "text" },
  external: ["react"],
  outfile: tmp,
  minify: false,
  sourcemap: false,
  logLevel: "info",
});

const code = fs.readFileSync(tmp, "utf8");
const wrapped =
`// dsh-xiaofei-memory client bundle (generated by build-client.mjs)
window.__ModuleLoader__.load({
  id: "dsh-xiaofei-memory",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    (function (require, module, exports) {
${code}
    })(require, module, exports);
    return module.exports;
  }
});
`;
fs.writeFileSync(out, wrapped);
fs.unlinkSync(tmp);
console.log(`built lib/client.js (${Buffer.byteLength(wrapped)} bytes)`);
