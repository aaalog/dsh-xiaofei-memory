// build.mjs — production build for dsh-xiaofei-memory.
//   backend:  src/index.js            -> dist/index.js         (ESM, node/peer externals)
//   frontend: src/client/index.tsx    -> dist/client/index.js  (window.__ModuleLoader__ bundle)
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const dist = path.join(root, "dist");
const clientDir = path.join(dist, "client");

// 1. Clean
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(clientDir, { recursive: true });

// 2. Backend bundle
await build({
  entryPoints: [path.join(root, "src", "index.js")],
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node22",
  external: ["node:*", "@deepseek-ai/*", "react"],
  outfile: path.join(dist, "index.js"),
  logLevel: "info",
  sourcemap: false,
});
console.log("backend: dist/index.js");

// 3. Frontend bundle (DSH module-loader format; CSS inlined as text)
const tmp = path.join(dist, ".client.cjs.js");
await build({
  entryPoints: [path.join(root, "src", "client", "index.tsx")],
  bundle: true,
  format: "cjs",
  platform: "browser",
  target: "es2020",
  jsx: "transform",
  loader: { ".css": "text" },
  external: ["react"],
  outfile: tmp,
  minify: false,
  sourcemap: false,
  logLevel: "info",
});
const code = fs.readFileSync(tmp, "utf8");
const wrapped =
`// dsh-xiaofei-memory client bundle (generated by build.mjs)
window.__ModuleLoader__.load({
  id: "dsh-xiaofei-memory",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    (function (require, module, exports) {
${code}
    })(require, module, exports);
    return module.exports;
  }
});
`;
fs.writeFileSync(path.join(clientDir, "index.js"), wrapped);
fs.unlinkSync(tmp);
console.log("frontend: dist/client/index.js");

console.log("build complete");
